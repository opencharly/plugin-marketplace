// skillfile_test.go — the `.agents/skills` reader's contract, GENERATOR side (leg L4).
//
// Every case here is discriminating in the strongest sense: `fillSkillFromFile` did not exist
// before this leg, so this file does not COMPILE against the pre-change tree. The cases then pin
// the three loud rules, because each of them guards against a published page disappearing or
// changing without anyone being told.

// writeSkillFile lays out one skill's file, in the shape the marketplace emitter produces (which is
// also the shape `extract` writes, minus the marker — the reader accepts both).
func writeSkillFile(t *testing.T, tree, dir, name, entry string) string {
	t.Helper()
	d := filepath.Join(tree, dir, name)
	if err := os.MkdirAll(d, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(d, "SKILL.md"), []byte(entry), 0o644); err != nil {
		t.Fatal(err)
	}
	return d
}

// TestFillSkillFromFile_ReadsTheMovedShape — the routing-only node plus the file its repo owns:
// the prose comes from the file, and the id defaults to the NODE name when the node declares none.
func TestFillSkillFromFile_ReadsTheMovedShape(t *testing.T) {
	tree := t.TempDir()
	const entry = "---\nname: git-workflow\ndescription: |-\n  branch-per-change, PR-only landing.\n---\n\n# git-workflow\n\nBody.\n"
	writeSkillFile(t, tree, ".agents/skills", "git-workflow", entry)

	s := spec.Skill{Family: "internals", Owner: "charly-internals"} // routing only, no name
	if err := fillSkillFromFile(&s, "git-workflow", tree, tree, []string{".agents/skills"}); err != nil {
		t.Fatalf("fillSkillFromFile: %v", err)
	}
	if want := "# git-workflow\n\nBody.\n"; s.Content != want {
		t.Errorf("content = %q, want %q", s.Content, want)
	}
	if want := "branch-per-change, PR-only landing."; s.Description != want {
		t.Errorf("description = %q, want %q", s.Description, want)
	}
	if strings.Contains(s.Content, "GENERATED by") {
		t.Error("the emitter's marker leaked into Content")
	}
}

// TestFillSkillFromFile_KeepsTheInlineBody — the transitional form every live entity still uses.
// A regression here would republish the whole corpus as empty.
func TestFillSkillFromFile_KeepsTheInlineBody(t *testing.T) {
	tree := t.TempDir()
	s := spec.Skill{Family: "internals", Owner: "charly-internals", Content: "# x\n", Description: "d"}
	if err := fillSkillFromFile(&s, "x", tree, tree, []string{".agents/skills"}); err != nil {
		t.Fatalf("the in-line body must keep working until the relocation's final leg: %v", err)
	}
	if s.Content != "# x\n" {
		t.Errorf("content was rewritten to %q", s.Content)
	}
}

// TestFillSkillFromFile_NoBodyAnywhereIsAnError — the one failure that would quietly DROP a
// published skill from the corpus.
func TestFillSkillFromFile_NoBodyAnywhereIsAnError(t *testing.T) {
	tree := t.TempDir()
	s := spec.Skill{Family: "internals", Owner: "charly-internals"}
	if err := fillSkillFromFile(&s, "ghost", tree, tree, []string{".agents/skills"}); err == nil {
		t.Fatal("a skill with neither an inline body nor a file was accepted — it would vanish from the corpus")
	}
}

// TestFillSkillFromFile_DisagreementIsAnError — two sources of truth for one published page is the
// ambiguity this whole relocation exists to remove, so it must fail loudly and name the skill.
func TestFillSkillFromFile_DisagreementIsAnError(t *testing.T) {
	tree := t.TempDir()
	writeSkillFile(t, tree, ".agents/skills", "x", "---\nname: x\n---\n\nFROM THE FILE\n")
	s := spec.Skill{Family: "internals", Owner: "charly-internals", Content: "FROM THE NODE\n"}
	err := fillSkillFromFile(&s, "x", tree, tree, []string{".agents/skills"})
	if err == nil {
		t.Fatal("a node's inline body disagreeing with its file was accepted")
	}
	if !strings.Contains(err.Error(), `"x"`) {
		t.Errorf("error %q does not name the skill", err)
	}
}

// TestFillSkillFromFile_HonoursADeclaredTree — spec#247's `#Candy.skills`: a repo that keeps its
// skills somewhere else is the reason the key exists.
func TestFillSkillFromFile_HonoursADeclaredTree(t *testing.T) {
	tree := t.TempDir()
	writeSkillFile(t, tree, "skills-here", "x", "---\nname: x\n---\n\nDECLARED TREE\n")
	s := spec.Skill{Family: "internals", Owner: "candy"}
	if err := fillSkillFromFile(&s, "x", tree, tree, []string{"skills-here"}); err != nil {
		t.Fatalf("a declared tree was not read: %v", err)
	}
	if s.Content != "DECLARED TREE\n" {
		t.Errorf("content = %q, want the declared tree's body", s.Content)
	}
}
