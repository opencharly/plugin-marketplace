package marketplace

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// extract_test.go — `marketplace extract`: the round trip and the no-op.
//
// The fixture uses the REAL authored shape, taken verbatim from a live owning repo
// (layer-charly-internals/charly.yml): the manifest holds a candy node and, beside it, one node per
// skill, keyed by its own name, whose single key `skill:` is the KIND discriminator. Inventing a
// different shape here is how a test passes while the tool fails on the only input that matters.

const extractManifest = `demo:
    candy:
        description: |-
            Fixture candy owning one skill entity.
        plan:
            - run: no-op fixture
              command: "true"
              context:
                - build
git-workflow:
    skill:
        name: git-workflow
        family: internals
        owner: demo
        description: |-
            branch-per-change landing.
        content: |
            # git-workflow

            Body.
        references:
            - name: validator-and-calver
              content: |
                The tag is cut at merge.
`

// writeExtractFixture lays out a repo root holding one skill entity, with the body in-line.
func writeExtractFixture(t *testing.T, manifest string) string {
	t.Helper()
	root := t.TempDir()
	if err := os.WriteFile(filepath.Join(root, "charly.yml"), []byte(manifest), 0o644); err != nil {
		t.Fatal(err)
	}
	return root
}

// TestExtract_MovesTheInlineBodyToTheAuthoredShape — the whole point of the verb: the body leaves
// the node and lands in the file its repo owns, in the shape the reader parses back (two-key
// frontmatter, no generator marker), with the references beside it and none of their own.
func TestExtract_MovesTheInlineBodyToTheAuthoredShape(t *testing.T) {
	root := writeExtractFixture(t, extractManifest)
	if err := extract(root); err != nil {
		t.Fatalf("extract: %v", err)
	}

	entry, err := os.ReadFile(filepath.Join(root, ".agents", "skills", "git-workflow", "SKILL.md"))
	if err != nil {
		t.Fatalf("the skill file was not written: %v", err)
	}
	if want := "---\nname: git-workflow\n"; !strings.HasPrefix(string(entry), want) {
		t.Errorf("frontmatter missing or wrong:\n%s", string(entry))
	}
	if !strings.Contains(string(entry), "# git-workflow\n\nBody.") {
		t.Errorf("the body did not move:\n%s", string(entry))
	}
	if strings.Contains(string(entry), "GENERATED by") {
		t.Error("the generator's marker leaked into a hand-owned file")
	}

	ref, err := os.ReadFile(filepath.Join(root, ".agents", "skills", "git-workflow", "references", "validator-and-calver.md"))
	if err != nil {
		t.Fatalf("the reference was not written: %v", err)
	}
	if strings.HasPrefix(string(ref), "---") {
		t.Errorf("references/ carry no frontmatter, by contract:\n%s", string(ref))
	}
	if strings.Contains(string(ref), "GENERATED by") {
		t.Error("the generator's marker leaked into a reference")
	}
}

// TestExtract_StopsMovingOnceTheBodyIsGone — the wave deletes the in-line body after the file
// exists; from that moment extract must move nothing. Proven by deleting the written file and
// re-running: a tool that still saw a body would put it back, and this asserts it does not.
func TestExtract_StopsMovingOnceTheBodyIsGone(t *testing.T) {
	root := writeExtractFixture(t, extractManifest)
	if err := extract(root); err != nil {
		t.Fatalf("extract: %v", err)
	}
	dir := filepath.Join(root, ".agents", "skills", "git-workflow")
	if err := os.RemoveAll(dir); err != nil {
		t.Fatal(err)
	}
	// The wave's step: the body and references are deleted from the node, leaving routing metadata.
	deleted := strings.Replace(extractManifest, "\n        content: |\n            # git-workflow\n\n            Body.", "", 1)
	deleted = strings.Replace(deleted, "        references:\n            - name: validator-and-calver\n              content: |\n                The tag is cut at merge.\n", "", 1)
	if deleted == extractManifest {
		t.Fatal("the fixture edit did not apply — this test would pass vacuously")
	}
	if err := os.WriteFile(filepath.Join(root, "charly.yml"), []byte(deleted), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := extract(root); err != nil {
		t.Fatalf("extract after the body was deleted: %v", err)
	}
	if _, err := os.Stat(dir); !os.IsNotExist(err) {
		t.Error("extract re-created a file for a node with no in-line body — it is not a no-op")
	}
}
